// src/services/tabEvictionPolicy.ts
//
// 标签的内存淘汰规则 —— **纯函数，不 import 任何 Tauri / React / 浏览器 API**。
//
// 为什么单独成文件：这条规则决定"哪些标签会被静默关掉"，而**静默关掉用户打开的
// 东西**是这一整块里唯一可能让人丢失现场的操作。规则必须能被脚本直接跑、
// 被穷举覆盖，而不是只能靠读代码相信它。
// 同样的理由见 `tabMountedPolicy.ts`（那里是"关闭即释放"，这里是"打开太久也回收"）。
//
// ============================================================
// 与「关闭即释放」「保活」的分工（三者别混为一谈）
// ============================================================
//
//   · **保活**：标签仍然打开、只是未被激活 -> 不卸载，现场（滚动位置、草稿）留着。
//   · **关闭即释放**：标签从标签栏消失 -> 卸载并释放组件缓存。语义正确性，不可关闭。
//   · **淘汰**（本文件）：标签仍然打开，但太久没被看过 -> 卸载。
//     这是**内存策略**：它拿"现场会丢"换"内存上限"，因此必须可配置、可保护。
//
// ============================================================
// 保护的层级：为什么是四级而不是两级
// ============================================================
//
// "不淘汰用户固定的标签"是最低要求，但只做两级会在两种常见情形下淘汰掉
// 用户根本不想丢的东西：
//
//   1. 用户正在看的两个标签（两组各自的激活项）**永远不能**被淘汰。
//      淘汰它等于当着用户的面把界面关掉 —— 那不是省内存，那是故障。
//   2. 收藏（`favorite_modules`）表达了"我常用的东西"。它比置顶弱一等
//      （收藏可能很多），但比"随手开过"强得多。
//
// 因此保护顺序是：**激活中 > 置顶 > 收藏 > 最近未见**。
// 这个顺序还有一条实际好处：越靠前的集合越小、判定越便宜，
// 而它们同时是"用户最在意"的那些 —— 保护最先判，代价最小、收益最大。
//
// ============================================================
// 为什么淘汰最久未**显示**的，而不是最久未打开的
// ============================================================
//
// 用户开着 A 打字、切到 B 查资料、又切回 A 继续打 —— A 是"最久未打开"的吗？
// 不是，它是刚刚才在用的。按"打开时间"淘汰会先把 A 干掉，而 A 正是用户在
// 反复使用的那一个。只有"最近一次被显示"能表达"用户现在更在意什么"。

/**
 * 一次淘汰判定的输入。
 *
 * 全部字段都是只读数组或集合 —— 规则不修改任何传入的数据。
 */
export interface EvictionInput {
  /** 第一组的标签（按显示顺序） */
  openTabs: readonly string[];
  /** 第二组的标签；空数组表示未分屏 */
  splitTabs: readonly string[];
  /** 第一组当前激活的标签 */
  activeTab: string | null;
  /** 第二组当前激活的标签 */
  splitActive: string | null;
  /** 已经挂载过的标签 */
  mountedTabs: readonly string[];
  /**
   * 每个标签**最后一次被显示**的时刻，值是一个单调递增的计数。
   *
   * 语义上等价于"最近使用顺序"，但用**时间戳**而不是数组位置表达，
   * 因为两者在"没有记录"这件事上不同：
   *   · 数组位置：不在数组里的标签没有位置，只能靠排序稳定性决定它排在哪 ——
   *     而那是一个**隐式**结果，改一次排序实现就会变；
   *   · 时间戳：没有记录就明确是 0，也就是"最久没被看过"，**显式**且可断言。
   *
   * 初版用的是数组位置，结果"从没被看过的标签"与"很久以前看过的标签"混在
   * 一起、靠 stable sort 碰巧排序正确 —— 而那条断言在写完的第一次运行里就
   * 暴露了这一点（见 `check-eviction.ts` 里对应的注释）。
   */
  lastSeen: Readonly<Record<string, number>>;
  /** 用户置顶的模块 ID */
  pinnedIds: readonly string[];
  /** 用户收藏的模块 ID */
  favoriteIds: readonly string[];
  /** 本次要腾出几个位置 */
  needed: number;
}

/** 规则需要的保护判据 */
type Protection = Pick<
  EvictionInput,
  'activeTab' | 'splitActive' | 'pinnedIds' | 'favoriteIds'
>;

/**
 * 判定某个标签是否受保护（不会被淘汰）。
 *
 * `selectEvictions` 与界面上的"哪些标签是安全的"共用**同一个**判据 ——
 * 两处各写一遍必然漂移，而漂移的表现是"界面说它安全，它却被淘汰了"。
 */
export function isProtectedFromEviction(moduleId: string, input: Protection): boolean {
  return (
    moduleId === input.activeTab ||
    moduleId === input.splitActive ||
    input.pinnedIds.includes(moduleId) ||
    input.favoriteIds.includes(moduleId)
  );
}

/**
 * 选出应当被淘汰的标签，按"应当先淘汰的在前"排列。
 *
 * 返回的数组长度不超过 `needed`，也可能为空 —— 空表示**没有可淘汰的对象**，
 * 调用方应当据此拒绝打开新标签并如实说明原因，而不是硬挤一个进去。
 *
 * 用"淘汰请求"而不是"淘汰一个"的接口，是为了让调用方不必循环调用本函数：
 * 循环调用会让每一次都重新做一遍筛选，而筛选的输入在循环中并不变化
 * （真正变化的只有调用方那边的标签集合）。
 */
export function selectEvictions(input: EvictionInput): string[] {
  if (input.needed <= 0) return [];

  // 按"最后一次被显示"的时刻升序：越久没看过的越先淘汰。
  //
  // 没有记录的标签取 0 —— 那是**最低**的时间戳，因此它们排在最前。
  // 这是刻意的：没有记录意味着用户从没看过它（从未被激活，或在很久以前
  // 就不再被碰过），因此它比"有记录但很旧"更该先被回收 ——
  // 后者至少证明用户用过它，它的现场可能还有价值。
  const candidates = [...input.openTabs, ...input.splitTabs].filter(
    (id) =>
      !isProtectedFromEviction(id, input) &&
      // 只有挂载过的标签才值得淘汰：没挂载过的标签不占面板内存，
      // 淘汰它只是白丢一个标签条目（用户少了一个标签，却没换到内存）。
      input.mountedTabs.includes(id)
  );

  candidates.sort((a, b) => {
    const left = input.lastSeen[a] ?? 0;
    const right = input.lastSeen[b] ?? 0;
    if (left !== right) return left - right;
    // 时刻相同时保持输入顺序（ES2019 起 `sort` 是稳定的）。
    // 稳定性在这里是正确性要求而不是优化：不确定的淘汰顺序会让同一台机器上
    // 两次淘汰选到不同的标签，而用户会看到界面在抖。
    return 0;
  });

  return candidates.slice(0, input.needed);
}
