// src/services/desktopShell.ts
//
// 桌面外壳（系统托盘与关闭行为）的前端门面。
//
// ============================================================
// 为什么需要"读回后端"这一条
// ============================================================
//
// 「关闭窗口时最小化到托盘」有**两个入口**：设置页里那个开关，以及托盘图标的
// 右键菜单。用户在托盘菜单里改过之后，前端那份设置缓存就变成了陈旧副本。
//
// 因此界面在打开设置时不能只信自己的缓存，必须向后端读一次真实值。
// 少了这一步，用户会遇到"我在托盘里关掉了这个选项，但设置页里它还开着" ——
// 而界面与实际行为相反，是最难被察觉的一类错误：用户会照着界面去推断行为。
//
// ============================================================
// 托盘不可用时必须如实说明
// ============================================================
//
// 托盘在部分环境下装不上（没有桌面会话、被系统策略禁用）。那时：
//   · 后端会把「隐藏到托盘」强制回落成「直接退出」并写回设置；
//   · 界面应当**显示回落后的值**，并说明原因。
//
// 一个"显示为已开启、实际什么都没做"的开关比"这个环境不支持"糟得多 ——
// 用户会以为窗口关掉之后自己仍能收到通知。

import { invoke } from '@tauri-apps/api/core';

/** 系统托盘在当前环境是否可用 */
export async function isTrayAvailable(): Promise<boolean> {
  try {
    return await invoke<boolean>('is_tray_available');
  } catch {
    // 命令不可用（旧版应用）= 没有托盘。不抛错：调用方要的是一个布尔判断，
    // 而"取不到"与"没有"在这里的后续行为完全相同。
    return false;
  }
}

/**
 * 读取后端的真实关闭行为。
 *
 * 托盘菜单可以改这一项，因此这个值可能与我们缓存里的不同 —— 这正是要读它的原因。
 */
export async function getCloseToTray(): Promise<boolean> {
  return invoke<boolean>('get_close_to_tray');
}

/**
 * 写回关闭行为，并让后端同步托盘菜单的勾选状态。
 *
 * 同步菜单勾选是后端那条命令的一部分，不是这里额外要做的事 ——
 * 少了它，用户会在设置页关掉这个开关、再右键托盘发现它还勾着。
 */
export async function setCloseToTray(enabled: boolean): Promise<boolean> {
  return invoke<boolean>('set_close_to_tray', { enabled });
}
