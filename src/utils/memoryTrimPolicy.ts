// src/utils/memoryTrimPolicy.ts
//
// 回收工作集的**策略**（不含任何 IPC）。
//
// 与 `utils/memoryLevelPolicy.ts` 分开成两个文件、而不是合成一个"内存策略"：
// 它们判据相同但**代价完全不同**，混在一起会让人以为它们是同一件事的两个开关。
//
//   · 内存目标等级：让引擎自己丢缓存/换出内容。可逆，代价小（切回来略微重算）；
//   · 回收工作集：把本进程树当前驻留的页交还系统。恢复时有一次**缺页**，
//     要等页面文件读回来 —— 对正被看着的窗口那表现为"点一下卡半拍"。
//
// 因此后者必须比前者更保守，判据必须被单独钉住。
//
// 为什么与 `services/memoryTrim.ts` 分开：那份服务要 import Tauri 的 IPC，
// 因此进不了 `tsconfig.node.json` 这个纯脚本 project，而门禁脚本只能核对它的
// **文本**。策略是这条链路里最容易被顺手放宽的部分（"最小化也回收吧，更省内存"），
// 所以它必须能被**直接运行**。
//
// 这个文件有一条硬约束：**不得 import 任何 Tauri / React / 浏览器 API**。

