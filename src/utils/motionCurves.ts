// src/utils/motionCurves.ts
//
// 浮层进出场用的缓动曲线。
//
// ---------------------------------------------------------------------------
// 为什么从 spring 换成了显式贝塞尔
//
// 侧边抽屉（插件详情、市场详情）原先用 `{ type: 'spring', stiffness: 380,
// damping: 38 }`。反馈是「速度不是线性，先慢再快，别扭」—— 这个描述是准确的，
// 而原因不在阻尼调得不好：
//
// **物理弹簧从静止出发，初速度必然为零。** 它先加速（前段位移很小、看起来
// 「慢」），到达峰值速度，再减速停下。所以「先慢 → 快 → 慢」是弹簧的固有
// 形状，无论怎么调参数都去不掉 —— 调低阻尼只会让它开始弹跳，调高阻尼只是
// 把中段压平。
//
// 而抽屉是**用户主动触发的一次性转场**，不是需要物理连续性的手势跟随。
// 这类转场该用的是「一开始就动起来、然后稳稳收住」的曲线：
// 起始速度高、无过冲、单调收敛。iOS 与 Material 的侧边面板都用这一族。
//
// 因此下面用显式 cubic-bezier：
//
//   · 进场 `[0.32, 0.72, 0, 1]`：控制点 2 的 y 已经很高（0.72），意味着
//     极早到达大部分位移 —— 第一帧就在动，观感是「果断地滑进来」。
//     这是 Material 的 emphasized-decelerate，也是 iOS sheet 的常用取值。
//   · 出场 `[0.4, 0, 1, 1]`：反过来，起步快、后段继续加速离场。
//     离场是「把它送走」，让它拖着一个温柔的尾巴只会显得迟钝。
//
// 时长 0.3s / 0.2s：进场略长以显得从容，出场略短 —— 用户已经决定关掉它了。
//
// ---------------------------------------------------------------------------
// 与「关闭界面动画」的关系
//
// 不需要在这里做判断。`x` 属于位移属性，framer-motion 的
// `MotionConfig reducedMotion="always"` 会把它短路掉（见 index.css 里关于
// `positionalKeys` 的说明），因此关掉动画时抽屉会直接出现在终态。
// ---------------------------------------------------------------------------

import type { Transition } from 'framer-motion';

/** 从右侧滑入的转场（抽屉、详情面板） */
export const DRAWER_ENTER: Transition = {
  duration: 0.3,
  ease: [0.32, 0.72, 0, 1],
};

/** 向右滑出的转场。比进场短：用户已经做了关闭的决定 */
export const DRAWER_EXIT: Transition = {
  duration: 0.2,
  ease: [0.4, 0, 1, 1],
};
