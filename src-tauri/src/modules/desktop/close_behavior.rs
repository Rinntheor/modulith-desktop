// src-tauri/src/modules/desktop/close_behavior.rs
//
// 主窗口的「关闭」到底意味着什么。
//
// ============================================================
// 为什么"关掉窗口"不能等于"退出程序"
// ============================================================
//
// 一旦应用有了在窗口之外继续工作的能力（后台插件、桌面通知），把两者等同起来
// 就会让那些能力全部失效：用户点一下关闭，后台任务跟着一起死。于是"后台保活"
// 这个功能从一开始就是假的 —— 它会在这条路径上被静默地取消掉。
//
// 因此关闭按钮的语义必须是一个**用户可见的选择**：
//   · 隐藏到托盘（默认）：应用继续在后台运行，托盘图标是把它叫回来的入口；
//   · 直接退出：与用户对关闭按钮的朴素预期一致。
//
// 这个选择存在持久设置里（`close_to_tray`），并且**托盘右键菜单里也能改** ——
// 两处改的是同一项，因为它是同一个字段。
//
// ============================================================
// 为什么拦截点只有一处
// ============================================================
//
// 窗口关闭只有 `CloseRequested` 一个入口，所以"某条路径漏了检查"在这里不可能
// 发生。这一点值得写下来：项目里已有的几类事故（释放挂钩漏调、权限检查漏点）
// 都是"同一件事有多个入口、而检查只挂在其中一部分上"。这里只有一个入口，
// 因此不需要一张检查清单。
//
// ============================================================
// 线程：这里的调用不会死锁
// ============================================================
//
// `CloseRequested` 回调跑在事件循环线程上，而 `window.hide()` 是**发完就走**
// 的请求（不等待事件循环执行结果）。会死锁的是"发完等回复"那一类
// （`with_webview`、`is_minimized()`），两者必须区分开 ——
// 否则会把"事件回调里什么都不能调"当成结论，把那类真正可用的 API 一起避开。
//
// ============================================================
// 为什么用 `WebviewWindow::on_window_event` 而不是 `Builder::on_window_event`
// ============================================================
//
// `Builder` 的那个版本能在闭包里拿到 `AppHandle`，但它必须在构建 builder 时
// 链式调用 —— 而 `lib.rs` 是生成文件（由 `generate-backend-module.ts` 产出），
// 在生成物里塞业务逻辑等于每次生成都可能被覆盖。
//
// `WebviewWindow::on_window_event` 的闭包拿不到 `AppHandle`，但这里可以在注册时
// 把它**捕获进来**（`AppHandle` 是 `Arc` 内部的廉价克隆，且闭包要求 `'static`，
// 捕获自己拥有的句柄正好合适）。这样既避开了生成文件，也不需要任何全局状态。
//
// ============================================================
// "直接退出"为什么必须显式 `exit`
// ============================================================
//
// 见下面那条分支里的说明。一句话：本应用除主窗口之外还有两个隐藏的辅助窗口，
// 因此**关掉主窗口不会让进程结束** —— 那不是"退出"，只是"窗口没了"。

use tauri::WindowEvent;

use crate::modules::settings::settings;
use crate::prelude::*;

/// 给主窗口装上关闭行为的判定
///
/// 在模块 `setup` 里调用一次。注册监听本身只是加一份回调，不做任何跨线程调用，
/// 因此在 setup 阶段（事件循环启动之前）执行是安全的。
pub fn install(app: &AppHandle) {
    let Some(window) = crate::core::window::main(&app) else {
        log::warn!("关闭行为：找不到主窗口，关闭时不会隐藏到托盘");
        return;
    };

    // 把应用句柄捕获进回调：后续每次关闭请求都要用它读设置。
    let app = app.clone();

    window.on_window_event(move |event| {
        // 只关心关闭请求；其余事件（焦点、尺寸、拖放）与关闭语义无关。
        let WindowEvent::CloseRequested { api, .. } = event else {
            return;
        };

        if !settings::load(&app).close_to_tray {
            // 用户的明确选择是"直接退出"。
            //
            // ============================================================
            // 为什么这里**必须**显式 `exit`，而不能只是"不拦截、让它自然关"
            // ============================================================
            //
            // 一开始这里写的是 `return`（不调 `prevent_close`，让默认行为发生），
            // 理由是"`app.exit(0)` 会跳过 Tauri 的正常关闭流程"。**那个理由是错的**，
            // 而且它导致了一个用户实际报出来的缺陷：选了"直接退出"，窗口是没了，
            // 但**进程还活着、托盘图标还在** —— 从用户的角度看就是"还是最小化到托盘"。
            //
            // 根因是本应用**不只有主窗口**：`tauri.conf.json` 里还声明了
            // `tray-menu` 与 `overlay` 两个 `visible: false` 的窗口，它们在启动时
            // 就真的被创建了。于是"关掉主窗口"永远不等于"所有窗口都关了"，
            // 事件循环照常转，进程自然不退出。
            //
            // 而"跳过正常关闭流程"这个顾虑并不成立：`lib.rs` 用的是 `run_return`，
            // 退出码那条路径上 `RunEvent::Exit` 会照常触发，模块收尾
            // （`registry.stop_all`，含后台宿主的优雅停止）与
            // `cleanup_before_exit` 都在那里。`app.exit` 正是走那条路。
            log::info!("关闭行为：用户选择了「直接退出」，结束进程");
            app.exit(0);
            return;
        }

        // 拦截关闭，改为隐藏。
        // 顺序很重要：`prevent_close()` 必须先调 —— 它是唯一能撤销"正在关闭"
        // 这个决定的地方，之后再做的任何事都只是善后。
        api.prevent_close();

        let Some(window) = crate::core::window::main(&app) else {
            return;
        };

        if let Err(error) = window.hide() {
            // 隐藏失败意味着窗口既没关掉也没藏起来，用户会看到"点了关闭没反应"。
            // 这时唯一诚实的补救是真的退出，而不是把窗口留在半死状态。
            log::warn!("关闭行为：隐藏窗口失败（{error}），改为直接退出");
            app.exit(0);
            return;
        }

        log::info!("窗口已隐藏到托盘，应用继续在后台运行（托盘菜单可退出）");
    });
}
